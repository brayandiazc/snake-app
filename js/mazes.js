export const DEFAULT_MAZE_ID = "libre";

export function getMaze(id) {
  return MAZES.find((maze) => maze.id === id) ?? getMaze(DEFAULT_MAZE_ID);
}

// Celdas de muro como índices (y * cols + x), para consultas rápidas.
export function wallsOf(maze) {
  const walls = new Set();
  maze.rows.forEach((row, y) => {
    [...row].forEach((cell, x) => {
      if (cell === "#") walls.add(y * row.length + x);
    });
  });
  return walls;
}
